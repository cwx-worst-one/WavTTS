def list_to_numbered_dict(lst):
    return {val: idx for idx, val in enumerate(lst)}


def append_additional_items_with_limit(original_list, additional_lst, limit=80):
    lst = original_list.copy()
    for additional_item in additional_lst:
        if len(lst) >= limit:
            break
        if additional_item in lst:
            continue
        lst.append(additional_item)
    return lst


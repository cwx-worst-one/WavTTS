from string import punctuation
from zhon.hanzi import punctuation as punctuation_zh

punctuation_zh = punctuation_zh
punctuation_en = punctuation.replace("'", "")

def _normalize_text(text):
    text = text.replace("&", " and ").replace("/", " ")
    return text.translate(str.maketrans("", "", punctuation_en)).strip()

def _remove_punc(text):
    # Remove all Chinese + English punctuation (but preserve apostrophe)
    all_punc = punctuation_zh + punctuation_en
    return re.sub(f"[{re.escape(all_punc)}]", "", text)

def _remove_cn_space(text):
    # Remove spaces between consecutive Chinese characters
    return re.sub(r'(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])', '', text)



class VocalTransforms(BaseTransforms):
    name = "VocalTransforms"
    data_sample_rate = 24000

    def __init__(
        self,
        sample_rate = 24000,
        audio_key: str = "wav",
        index_key: str = "meta",
        normalize_audio: bool = False,
        tokenizer = None,
        frame_rate: int = 25,
        min_duration=30,
        max_duration=600,
        extra_audio_keys = None,
        line_break_symbol = None,
    ):
        super().__init__()
        self.sample_rate = sample_rate
        self.audio_key = audio_key
        self.index_key = index_key
        self.tokenizer = tokenizer
        self.min_duration = min_duration
        self.max_duration = max_duration
        self.frame_rate = frame_rate
        base_transforms = [ToTensor(), SetAudioDimensions(), NormalizeAudioToFloat32()]
        self.resampler = {}
        self.fast_normalizer = FastNormalizeAudio()
        self.normalize_audio = normalize_audio
        self.base_transform = Compose(base_transforms)
        if line_break_symbol is None:
            self.line_break_symbol = "," # will be removed
        else:
            self.line_break_symbol = " "
        

    def resample(self, src_sample_rate, x):
        if src_sample_rate == self.sample_rate:
            return x

        if src_sample_rate not in self.resampler:
            self.resampler[src_sample_rate] = Resample(
                src_sample_rate, self.sample_rate
            )
        return self.resampler[src_sample_rate](x)

    def remove_punc(self, text):
        punctuation_all = list(punctuation_zh + punctuation)
        for punc in punctuation_all:
            text = text.replace(punc, "")
        return text

    def get_audio(self, item):
        name = item["__dataset_name__"]
        # if re.match("music_.*", name):
        #     src_sample_rate = self.data_sample_rate
        # else:
        src_sample_rate = item["src_sample_rate"]
        
        if re.match(".*karaoke.*", name):
            self.audio_key = 'vocal'
        else:
            self.audio_key = 'wav'

        audio = self.base_transform(item[self.audio_key])
        audio = self.resample(src_sample_rate, audio)
        if self.normalize_audio:
            audio = self.fast_normalizer(audio)
        return audio

    def get_text_token(self, text):
        """
        Args:
            self: The object instance.
            text (str): The input text string.

        Returns:
            tuple: A tuple containing:
                - torch.Tensor: The tensor of token IDs.
                - torch.Tensor: The tensor of the attention mask.
                - str: The processed text.
        """
        
        processed_text = self.remove_punc(normalize_text(str(text)))
        
        # following is the same with data loader
        #text = str(text)
        #processed_text = _normalize_text(text)
        #processed_text = _remove_punc(text)
        #processed_text = _remove_cn_space(text)

        if len(processed_text) >= 512:
            token_chunks = []
            mask_chunks = []
            for i in range(0, len(processed_text), 512):
                
                encoded_chunk = self.tokenizer(
                    processed_text[i:i+512], 
                    add_special_tokens=False, 
                    return_tensors="pt"
                )
                
                token_chunks.append(encoded_chunk["input_ids"].squeeze(dim=0))
                mask_chunks.append(encoded_chunk["attention_mask"].squeeze(dim=0))
                
            token = torch.cat(token_chunks, dim=0)
            attn_mask = torch.cat(mask_chunks, dim=0)
        else:

            encoded_text = self.tokenizer(
                processed_text, 
                add_special_tokens=False, 
                return_tensors="pt"
            )
     
            token = encoded_text["input_ids"].squeeze(dim=0)
            attn_mask = encoded_text["attention_mask"].squeeze(dim=0)
            

        return token, attn_mask, processed_text

    def get_text(self, item):
        meta = item[self.index_key]
        if isinstance(meta, str):
            meta = json.loads(meta)

        utterances = parse_utterance_lyrics(meta)
        full_text = self.line_break_symbol.join([u["text"] for u in utterances])
        
        structure_tags = parse_structure_tags_custom_concat(meta)
        if structure_tags is None:
            song_slices = transform_utts_to_song_slices_heuristic(utterances, 
                                                                  min_duration=self.min_duration, max_duration=self.max_duration, 
                                                                  language='Chinese')
        else:
            # todo: merge with AR latest codebase
            song_slices = transform_utts_to_song_slices_structure(utterances, min_duration=self.min_duration, max_duration=self.max_duration,
                                                structure_tags=structure_tags.tags, slice_mode='section', language='Chinese')
            
        ok_song_slices = []
        for i in range(len(song_slices)):
            if song_slices[i].duration < self.min_duration:
                continue
            text = self.line_break_symbol.join(
                [phrase.text.replace(" ", "") for phrase in song_slices[i].phrases if phrase.text is not None \
                 and ((phrase.lyrics_confidence is not None and phrase.lyrics_confidence > 0.6) \
                 or phrase.lyrics_confidence is None)])
            # text = self.line_break_symbol.join(
            #     [phrase.text for phrase in song_slices[i].phrases if phrase.text is not None \
            #      and phrase.lyrics_confidence > 0.6])
            song_slices[i].text = text
            ok_song_slices.append(song_slices[i])

        if len(ok_song_slices) == 0:
            if len(song_slices) == 1:
                ok_song_slices = song_slices
                if song_slices[0].phrases[0].text is None:
                    song_slices[0].text = ""
                else:
                    song_slices[0].text = song_slices[0].phrases[0].text.replace(" ", "")
            else:
                song_slice = SongSlice(
                    phrases=[Phrase(text=None, time_span=[0, meta["duration"]])],
                )
                song_slice.text = ''
                ok_song_slices = [song_slice]
        
        full_len_song_slice = ok_song_slices[0]
        for i in range(len(ok_song_slices[1:])):
            if ok_song_slices[i].duration > full_len_song_slice.duration:
                full_len_song_slice = ok_song_slices[i]
        
        return full_len_song_slice, full_text
        

    def __call__(self, item: Dict[str, Any]) -> Generator:
        # try:
        full_song_slice, full_text = self.get_text(item)
        # except Exception as e:
        #     self._update_stats(skipped=True, message=f"Error loading text: {e}")
        #     return
        # try:
        audio = self.get_audio(item)
        # except Exception as e:
        #     self._update_stats(skipped=True, message=f"Error loading audio: {e}")
        #     return
        audio_length = torch.tensor([audio.shape[-1]], dtype=torch.long)
        output_dict = {"audio": audio, 
                    "audio_length": audio_length}
        output_dict["slice"] = full_song_slice
        
        if self.tokenizer is not None and callable(self.tokenizer):
            token, token_attn_mask, normalized_text = self.get_text_token(full_text)
            if (
                token.size(-1)
                > math.floor(audio.size(-1) / self.sample_rate) * self.frame_rate
            ):
                self._update_stats(skipped=True, message="Token too long")
                return
            output_dict.update(token=token)
            output_dict.update(text=normalized_text)
            output_dict.update(token_padding_mask=token_attn_mask)
            output_dict["no_lyric_flag"] = True if len(full_text) == 0 else False
        yield output_dict
        self._update_stats(skipped=False)

def collate_fn(batch: List) -> Dict[str, torch.Tensor]:
    return batch[0]

class VocalParquetDataset(WebPipeline):
    name = "VocalParqueDataset"

    def __init__(
        self,
        transforms: VocalTransforms,
        data_id: int = 3520, 
        url_pattern: str = None,
        extra_audio_keys=None,
        **kwargs,
    ):
        extra_audio_keys = [] if extra_audio_keys is None else extra_audio_keys
        print(f"[{self.name}] initializing...")
        dataset = ParquetDataset(data_id=data_id, data_urls=url_pattern,
                                 extra_fields_in_data=extra_audio_keys, **kwargs)
        preprocessor = WebDatasetBufferPreprocessor(transforms=transforms)
        print(f"[{self.name}] MultiIterableDataset constructing...")
        pipeline = [{"compose": [preprocessor.train_buffer_preprocessor]}]
        super().__init__(dataset, pipeline)
        print(f"[{self.name}] initialized.")

class EvalDataset(pl.LightningDataModule):
    def __init__(
        self, 
        data_id,
        tokenizer=None,
        url_pattern=None,
        frame_rate=25,
        sample_rate=24000,
        num_worker=1,
        batch_size=1,
        min_duration=60,
        max_duration=600,
    ):
        pl.LightningDataModule.__init__(self)
        self.data_id = data_id
        if tokenizer is not None:
            self.tokenizer = BertTokenizer.from_pretrained(tokenizer)
        else:
            self.tokenizer = None
        self.transform = VocalTransforms(
            sample_rate=sample_rate,
            tokenizer=self.tokenizer,
            frame_rate=frame_rate,
            min_duration=min_duration,
            max_duration=max_duration,
        )
        self.dataset = VocalParquetDataset(
                transforms=self.transform,
                data_id=data_id,
                resampled=False,
                handler=wds.warn_and_continue,
            )
        self.dataloader = DataLoader(self.dataset,
                                     num_workers=num_worker, 
                                     batch_size=batch_size,
                                     collate_fn=collate_fn)
        

def test_logfbank():
    '''Only support batch = 1'''
    waveform = _get_waveform()
    fn = LogFbank(fbank_dim=26, window_type='povey')
    item = dict()
    sample_rate = 16000
    item['waveform'] = waveform
    item['sample_rate'] = sample_rate
    fbank1 = torch.from_numpy(fn(item)['fbank'])
    fbank2 = _get_out()
    assert torch.allclose(fbank1, fbank2, atol=1e-2)


